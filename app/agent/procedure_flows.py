        "2. 确认自己是否符合申请年级、成绩、课程修读、处分记录等要求。\n"
        "3. 确认拟转入学院和专业是否接收，以及是否需要参加考核。\n\n"
        "所需材料：\n"
        "1. 转专业申请表。\n"
        "2. 学生本人基本信息，包括姓名、学号、当前学院和专业。\n"
        "3. 拟申请转入学院和专业。\n"
        "4. 已修课程成绩或成绩单。\n"
        "5. 转专业申请理由。\n"
        "6. 如涉及特殊情况，可能需要补充处分、休学、保留学籍等相关说明材料。\n\n"
        "办理流程：\n"
        "1. 查看学校转专业通知和接收专业计划。\n"
        "2. 判断自己是否符合申请条件。\n"
