        "4. 所在学院进行初审。\n"
        "5. 拟转入学院组织考核或审核。\n"
        "6. 等待学校公示和最终审批结果。\n"
        "7. 审批通过后，按要求办理课程认定、学分替代和选课调整。\n\n"
